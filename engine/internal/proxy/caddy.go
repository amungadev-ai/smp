// Package proxy configures Caddy through its admin API. Domains get automatic
// HTTPS: a site block per domain, Caddy obtains and renews certificates.
package proxy

import (
	"bytes"
	"fmt"
	"net/http"
 "net/url"
 "strings"
 "io"
	"sync"
	"time"

	"drevanta/engine/internal/model"
)

const AdminURL = "http://127.0.0.1:2019"

const (
	ModeCaddy = "caddy"
	ModeMock  = "mock"
)

type Caddy struct {
	adminURL string
	mock     bool
	client   *http.Client

	mu     sync.Mutex
	routes []string // mock-mode mirror of configured domains
}

func New() *Caddy {
	c := &Caddy{adminURL: AdminURL, client: &http.Client{Timeout: 5 * time.Second}}
	if !c.probe() {
		c.mock = true
	}
	return c
}

func (c *Caddy) probe() bool {
	resp, err := c.client.Get(c.adminURL + "/config/")
	if err != nil {
		return false
	}
	resp.Body.Close()
	return resp.StatusCode >= 200 && resp.StatusCode < 300
}

func (c *Caddy) Mode() string {
	if c.mock {
		return ModeMock
	}
	return ModeCaddy
}

// NewWithURL targets a dedicated Caddy admin endpoint (also used for tests).
func NewWithURL(url string)*Caddy{return &Caddy{adminURL:url,client:&http.Client{Timeout:5*time.Second}}}

// NewMock forces simulated routing (lab/CI use, or --mock flag).
func NewMock() *Caddy {
	return &Caddy{adminURL: AdminURL, client: &http.Client{Timeout: 5 * time.Second}, mock: true}
}

func (c *Caddy) Reachable() bool { return !c.mock }
// Ping verifies a successful admin response; construction alone is not readiness.
func (c *Caddy) Ping() bool { return !c.mock && c.probe() }

// HasRoute reports whether a domain is currently routed (mock mirror; in real
// mode the authoritative answer comes from ApplyConfig success).
func (c *Caddy) HasRoute(domain string) bool {
	c.mu.Lock()
	defer c.mu.Unlock()
	for _, r := range c.routes {
		if r == domain {
			return true
		}
	}
	return false
}

// ApplyConfig regenerates the full Caddy configuration from engine state.
// Full-config POSTs keep the admin API state consistent with our store.
func (c *Caddy) ApplyConfig(domains []model.Domain, projects []model.Project) error {
	cfg := c.BuildConfig(domains,projects)
	if c.mock {
		c.mu.Lock()
		c.routes = c.routes[:0]
		for _, d := range domains {
            for _,p:=range projects{if d.ProjectID==p.ID && p.CurrentRelease!="" && p.UpstreamPort>0 {c.routes=append(c.routes,d.Name);break}}
		}
		c.mu.Unlock()
		return nil
	}
	resp, err := c.client.Post(c.adminURL+"/load", "text/caddyfile", bytes.NewBufferString(cfg))
	if err != nil {
		return fmt.Errorf("caddy admin API unreachable: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode >= 300 {
		raw,_:=io.ReadAll(io.LimitReader(resp.Body,1024))
        return fmt.Errorf("caddy /load returned %d: %s", resp.StatusCode,string(raw))
	}
	return nil
}

// BuildConfig keeps the dedicated Caddy administration listener on its
// explicit port. Otherwise a full /load would move it back to shared :2019.
func (c *Caddy) BuildConfig(domains []model.Domain,projects []model.Project)string{
 cfg:=BuildCaddyfile(domains,projects)
 u,err:=url.Parse(c.adminURL)
 if err==nil&&u.Hostname()=="127.0.0.1"&&u.Port()!=""{
  cfg=strings.Replace(cfg,"\tadmin 127.0.0.1:2019\n","\tadmin "+u.Host+"\n",1)
 }
 return cfg
}

// BuildCaddyfile renders the configuration the engine would load. Also written
// to disk on the VPS as a reference and for bootstrapping before the admin API
// is up.
func BuildCaddyfile(domains []model.Domain, projects []model.Project) string {
	var out bytes.Buffer
	out.WriteString("# generated by drevanta engine — do not edit by hand\n")
	out.WriteString("{\n\tadmin 127.0.0.1:2019\n}\n\n")
	byID := make(map[string]model.Project, len(projects))
	for _, p := range projects {
		byID[p.ID] = p
	}
	for _, d := range domains {
		if d.ProjectID == "" {
			continue
		}
		p, ok := byID[d.ProjectID]
		if !ok || p.CurrentRelease=="" || p.UpstreamPort<1 || p.UpstreamPort>65535 {
			continue
		}
		host := d.Name
		if d.Scheme != "https" {
			host = "http://" + d.Name
		}
		fmt.Fprintf(&out, "%s {\n\treverse_proxy 127.0.0.1:%d\n}\n\n", host, p.UpstreamPort)
	}
	return out.String()
}
